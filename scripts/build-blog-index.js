#!/usr/bin/env node
/**
 * Generates js/blog-index.js — a metadata-only copy of BLOG_POSTS for pages that
 * only render blog *cards* (currently the homepage carousel).
 *
 * Why: js/blog.js is ~287KB, and ~62% of that is the full markdown body of every
 * post. The homepage never reads `content`, `faqs`, `schema` or `promo`, but it
 * paid to download, parse and compile all of it just to show 5 card titles.
 *
 * Run this after adding or editing a post in js/blog.js:
 *     node scripts/build-blog-index.js
 *
 * Keep CARD_FIELDS in sync with the carousel markup in index.html.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'js', 'blog.js');
const OUT = path.join(ROOT, 'js', 'blog-index.js');

// Only the fields the card renderer actually touches.
const CARD_FIELDS = ['slug', 'title', 'date', 'excerpt', 'image', 'cardAspectRatio', 'categories'];

/** Extract the `const BLOG_POSTS = [ ... ];` literal without executing the DOM code around it. */
function extractPostsArray(src) {
  const start = src.indexOf('const BLOG_POSTS');
  if (start === -1) throw new Error('Could not find `const BLOG_POSTS` in js/blog.js');

  const open = src.indexOf('[', start);
  let depth = 0;
  let inString = null;

  for (let i = open; i < src.length; i++) {
    const ch = src[i];
    const prev = src[i - 1];

    if (inString) {
      if (ch === inString && prev !== '\\') inString = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') {
      inString = ch;
      continue;
    }
    if (ch === '[') depth++;
    else if (ch === ']') {
      depth--;
      if (depth === 0) return src.slice(open, i + 1);
    }
  }
  throw new Error('Unterminated BLOG_POSTS array literal');
}

const source = fs.readFileSync(SRC, 'utf8');

// SAFETY: eval() here is deliberate and scoped.
//   - Input is js/blog.js, first-party source committed to this repo. It is never
//     user input, never fetched at runtime, and never reaches a browser.
//   - This script runs only by hand at build time, never in a Netlify Function
//     or on any request path.
//   - JSON.parse() cannot substitute: the array is a JS literal (unquoted keys,
//     template literals, trailing commas), not JSON.
// If blog.js ever becomes externally sourced, replace this with a real JS parser.
// eslint-disable-next-line no-eval
const posts = eval(extractPostsArray(source));

if (!Array.isArray(posts) || posts.length === 0) {
  throw new Error('BLOG_POSTS parsed to an empty array — refusing to write blog-index.js');
}

const slim = posts.map((post) => {
  const out = {};
  for (const field of CARD_FIELDS) {
    if (post[field] !== undefined) out[field] = post[field];
  }
  if (!out.slug || !out.title) {
    throw new Error(`Post is missing slug or title: ${JSON.stringify(post).slice(0, 120)}`);
  }
  return out;
});

const banner = `/* AUTO-GENERATED by scripts/build-blog-index.js — do not edit by hand.
   Metadata-only view of BLOG_POSTS for card rendering (homepage carousel).
   Full post bodies live in js/blog.js, which only the blog pages load.
   Regenerate with: node scripts/build-blog-index.js */\n`;

const body = `const BLOG_POSTS = ${JSON.stringify(slim, null, 2)};\n`;

fs.writeFileSync(OUT, banner + body);

const srcSize = Buffer.byteLength(source);
const outSize = Buffer.byteLength(banner + body);
console.log(`blog-index.js written: ${slim.length} posts`);
console.log(`  js/blog.js       ${srcSize.toLocaleString()} B`);
console.log(`  js/blog-index.js ${outSize.toLocaleString()} B  (${(100 - (outSize / srcSize) * 100).toFixed(1)}% smaller)`);
